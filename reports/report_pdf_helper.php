
<?php

if (!function_exists('reportFail')) {
    function reportFail($message, $status = 400)
    {
        while (ob_get_level() > 0) {
            ob_end_clean();
        }

        http_response_code($status);
        exit($message);
    }
}

if (!function_exists('reportDateIsValid')) {
    function reportDateIsValid($value)
    {
        if (!is_string($value)) {
            return false;
        }

        $date = DateTime::createFromFormat('!Y-m-d', $value);
        $errors = DateTime::getLastErrors();

        return $date !== false
            && ($errors === false || (
                $errors['warning_count'] === 0 &&
                $errors['error_count'] === 0
            ))
            && $date->format('Y-m-d') === $value;
    }
}

if (!function_exists('reportCreatePdf')) {
    function reportCreatePdf(
        $title,
        $dateFrom,
        $dateTo,
        $generatedBy,
        $generatedAt,
        $recipient,
        $tableHtml,
        $filename
    ) {
        $pdf = new TCPDF('L', 'mm', 'A4', true, 'UTF-8', false);

        $pdf->SetCreator('Inventory and Sales Management System');
        $pdf->SetAuthor($generatedBy);
        $pdf->SetTitle($title);
        $pdf->SetMargins(10, 12, 10);
        $pdf->SetAutoPageBreak(true, 18);
        $pdf->SetFont('dejavusans', '', 9);
        $pdf->AddPage();

        $recipientDisplay = $recipient !== ''
            ? $recipient
            : '________________________';

        $html = '
        <h2 style="text-align:center;">MVM DAEGU SUPERMARKET CORP.</h2>
        <h3 style="text-align:center;">' .
            htmlspecialchars($title, ENT_QUOTES, 'UTF-8') .
        '</h3>
        <p style="text-align:center;">Reporting Period: ' .
            htmlspecialchars(date('F j, Y', strtotime($dateFrom)), ENT_QUOTES, 'UTF-8') .
            ' to ' .
            htmlspecialchars(date('F j, Y', strtotime($dateTo)), ENT_QUOTES, 'UTF-8') .
        '</p>
        <br>' . $tableHtml . '
        <br><br>
        <table cellpadding="5">
            <tr>
                <td width="50%">
                    Generated by:<br><br><br>
                    <b>' . htmlspecialchars($generatedBy, ENT_QUOTES, 'UTF-8') . '</b><br>
                    System User<br>
                    Generated on: ' . htmlspecialchars($generatedAt, ENT_QUOTES, 'UTF-8') . '
                </td>
                <td width="50%">
                    Presented to / Received by:<br><br><br>
                    <b>' . htmlspecialchars($recipientDisplay, ENT_QUOTES, 'UTF-8') . '</b><br>
                    Signature: ______________________________<br><br>
                    Date received: __________________________
                </td>
            </tr>
        </table>';

        $pdf->writeHTML($html, true, false, true, false, '');

        while (ob_get_level() > 0) {
            ob_end_clean();
        }

        $pdf->Output($filename, 'I');
        exit;
    }
}

if (!function_exists('reportEscape')) {
    function reportEscape($value)
    {
        return htmlspecialchars((string)$value, ENT_QUOTES, 'UTF-8');
    }
}

if (!function_exists('reportMoney')) {
    function reportMoney($value)
    {
        return '₱' . number_format((float)$value, 2);
    }
}

if (!function_exists('reportGetRequestDetails')) {
    function reportGetRequestDetails()
    {
        $dateFrom = $_GET['date_from'] ?? '';
        $dateTo = $_GET['date_to'] ?? '';
        $recipient = trim((string)($_GET['recipient'] ?? ''));

        $recipient = function_exists('mb_substr')
            ? mb_substr($recipient, 0, 150)
            : substr($recipient, 0, 150);

        if (!reportDateIsValid($dateFrom) || !reportDateIsValid($dateTo)) {
            reportFail('Please provide valid start and end dates.');
        }

        if ($dateFrom > $dateTo) {
            reportFail('The start date cannot be later than the end date.');
        }

        $generatedBy = trim((string)(
            $_SESSION['userName'] ??
            $_SESSION['username'] ??
            $_SESSION['user_name'] ??
            ''
        ));

        if ($generatedBy === '') {
            $generatedBy = 'Authenticated System User';
        }

        return [
            'date_from' => $dateFrom,
            'date_to' => $dateTo,
            'recipient' => $recipient,
            'generated_by' => $generatedBy,
            'generated_at' => date('F j, Y g:i A')
        ];
    }
}

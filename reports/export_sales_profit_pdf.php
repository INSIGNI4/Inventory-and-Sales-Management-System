
<?php
ob_start();

if (session_status() !== PHP_SESSION_ACTIVE) {
    session_start();
}

date_default_timezone_set('Asia/Manila');

require_once __DIR__ . '/../connect.php';
require_once __DIR__ . '/../tcpdf/tcpdf.php';

function reportFail($message, $status = 400)
{
    while (ob_get_level() > 0) {
        ob_end_clean();
    }

    http_response_code($status);
    exit($message);
}

function reportDateIsValid($value)
{
    if (!is_string($value)) {
        return false;
    }

    $date = DateTime::createFromFormat('!Y-m-d', $value);
    $errors = DateTime::getLastErrors();

    return $date !== false
        && ($errors === false || (
            $errors['warning_count'] === 0 &&
            $errors['error_count'] === 0
        ))
        && $date->format('Y-m-d') === $value;
}

function reportCreatePdf(
    $title,
    $dateFrom,
    $dateTo,
    $generatedBy,
    $generatedAt,
    $recipient,
    $tableHtml,
    $filename
) {
    $pdf = new TCPDF('L', 'mm', 'A4', true, 'UTF-8', false);

    $pdf->SetCreator('Inventory and Sales Management System');
    $pdf->SetAuthor($generatedBy);
    $pdf->SetTitle($title);
    $pdf->SetMargins(10, 12, 10);
    $pdf->SetAutoPageBreak(true, 18);
    $pdf->SetFont('dejavusans', '', 10);
    $pdf->AddPage();

    $recipientDisplay = $recipient !== ''
        ? $recipient
        : '________________________';

    $html = '
    <h2 style="text-align:center;">MVM DAEGU SUPERMARKET CORP.</h2>
    <h3 style="text-align:center;">' .
        htmlspecialchars($title, ENT_QUOTES, 'UTF-8') .
    '</h3>
    <p style="text-align:center;">Reporting Period: ' .
        htmlspecialchars(date('F j, Y', strtotime($dateFrom)), ENT_QUOTES, 'UTF-8') .
        ' to ' .
        htmlspecialchars(date('F j, Y', strtotime($dateTo)), ENT_QUOTES, 'UTF-8') .
    '</p><br>' . $tableHtml . '<br><br>
    <table cellpadding="5">
        <tr>
            <td width="50%">
                Generated by:<br><br><br>
                <b>' . htmlspecialchars($generatedBy, ENT_QUOTES, 'UTF-8') . '</b><br>
                System User<br>
                Generated on: ' . htmlspecialchars($generatedAt, ENT_QUOTES, 'UTF-8') . '
            </td>
            <td width="50%">
                Presented to / Received by:<br><br><br>
                <b>' . htmlspecialchars($recipientDisplay, ENT_QUOTES, 'UTF-8') . '</b><br>
                Signature: ______________________________<br><br>
                Date received: __________________________
            </td>
        </tr>
    </table>';

    $pdf->writeHTML($html, true, false, true, false, '');

    while (ob_get_level() > 0) {
        ob_end_clean();
    }

    $pdf->Output($filename, 'I');
    exit;
}

$dateFrom = $_GET['date_from'] ?? '';
$dateTo = $_GET['date_to'] ?? '';
$recipient = trim((string)($_GET['recipient'] ?? ''));

$recipient = function_exists('mb_substr')
    ? mb_substr($recipient, 0, 150)
    : substr($recipient, 0, 150);

if (!reportDateIsValid($dateFrom) || !reportDateIsValid($dateTo)) {
    reportFail('Please provide valid start and end dates.');
}

if ($dateFrom > $dateTo) {
    reportFail('The start date cannot be later than the end date.');
}

$generatedBy = trim((string)(
    $_SESSION['userName'] ??
    $_SESSION['username'] ??
    $_SESSION['user_name'] ??
    ''
));

if ($generatedBy === '') {
    $generatedBy = 'Authenticated System User';
}

$generatedAt = date('F j, Y g:i A');

try {
    if (
        !isset($conn, $conn_pos) ||
        !($conn instanceof mysqli) ||
        !($conn_pos instanceof mysqli)
    ) {
        throw new RuntimeException(
            'The login or point_of_sale database connection is unavailable.'
        );
    }

    $salesSql = "
        SELECT
            si.Product_ID,
            SUM(COALESCE(si.Quantity, 0)) AS units_sold,
            SUM(
                COALESCE(si.`Unit_Price`, 0) *
                COALESCE(si.Quantity, 0)
            ) AS revenue
        FROM sales_item_test si
        INNER JOIN sales_test sh
            ON sh.Sales_ID = si.Sales_ID
        WHERE sh.date_created >= ?
          AND sh.date_created < DATE_ADD(?, INTERVAL 1 DAY)
        GROUP BY si.Product_ID
        ORDER BY si.Product_ID
    ";

    $salesStmt = $conn_pos->prepare($salesSql);

    if (!$salesStmt) {
        throw new RuntimeException(
            'Sales query preparation failed: ' . $conn_pos->error
        );
    }

    $salesStmt->bind_param('ss', $dateFrom, $dateTo);

    if (!$salesStmt->execute()) {
        throw new RuntimeException(
            'Sales query execution failed: ' . $salesStmt->error
        );
    }

    $salesResult = $salesStmt->get_result();

    $costSql = "
        SELECT
            r.Product_ID,
            r.Quantity AS ordered_quantity,
            r.PurchaseUnitCost
        FROM restock r
        INNER JOIN (
            SELECT
                Product_ID,
                MAX(Orestock_ID) AS LatestRestockID
            FROM restock
            WHERE Status <> 'Cancelled'
              AND PurchaseUnitCost IS NOT NULL
              AND PurchaseUnitCost >= 0
            GROUP BY Product_ID
        ) latest
            ON latest.LatestRestockID = r.Orestock_ID
    ";

    $costResult = $conn->query($costSql);

    if (!$costResult) {
        throw new RuntimeException(
            'Purchase cost query failed: ' . $conn->error
        );
    }

    $restockCosts = [];

    while ($costRow = $costResult->fetch_assoc()) {
        $restockCosts[(int)$costRow['Product_ID']] = [
            'ordered_quantity' => (int)$costRow['ordered_quantity'],
            'unit_cost' => (float)$costRow['PurchaseUnitCost']
        ];
    }

    $costResult->free();

    $productSql = "
        SELECT ProductName
        FROM product
        WHERE Product_ID = ?
        LIMIT 1
    ";

    $productStmt = $conn->prepare($productSql);

    if (!$productStmt) {
        throw new RuntimeException(
            'Product query preparation failed: ' . $conn->error
        );
    }

    $totalRevenue = 0;
    $totalCost = 0;
    $totalUnits = 0;
    $totalProfit = 0;
    $missingCostProducts = 0;
    $productCount = 0;

    $html = '
    <table border="1" cellpadding="5">
        <tr style="font-weight:bold;background-color:#eeeeee;">
            <th width="32%">Product</th>
            <th width="12%">Units Sold</th>
            <th width="18%">Revenue</th>
            <th width="19%">Estimated Product Cost</th>
            <th width="19%">Estimated Gross Profit</th>
        </tr>';

    while ($row = $salesResult->fetch_assoc()) {
        $productId = (int)$row['Product_ID'];
        $units = (float)$row['units_sold'];
        $revenue = (float)$row['revenue'];

        $productName = 'Unknown Product';

        $productStmt->bind_param('i', $productId);

        if (!$productStmt->execute()) {
            throw new RuntimeException(
                'Product lookup execution failed: ' . $productStmt->error
            );
        }

        $productResult = $productStmt->get_result();

        if ($productRow = $productResult->fetch_assoc()) {
            if ($productRow['ProductName'] !== null) {
                $productName = $productRow['ProductName'];
            }
        }

        $productResult->free();

        $hasCost = isset($restockCosts[$productId]);

        if ($hasCost) {
            $orderedQuantity = $restockCosts[$productId]['ordered_quantity'];
            $unitCost = $restockCosts[$productId]['unit_cost'];

            $cost = $unitCost * $orderedQuantity;
            $profit = $revenue - $cost;

            $totalCost += $cost;
            $totalProfit += $profit;
        } else {
            $cost = null;
            $profit = null;
            $missingCostProducts++;
        }

        $totalUnits += $units;
        $totalRevenue += $revenue;
        $productCount++;

        $costDisplay = $hasCost
            ? '₱' . number_format($cost, 2)
            : 'N/A';

        $profitDisplay = $hasCost
            ? '₱' . number_format($profit, 2)
            : 'N/A';

        $html .= '
        <tr>
            <td>' . htmlspecialchars((string)$productName, ENT_QUOTES, 'UTF-8') . '</td>
            <td align="right">' . number_format($units, 0) . '</td>
            <td align="right">₱' . number_format($revenue, 2) . '</td>
            <td align="right">' . $costDisplay . '</td>
            <td align="right">' . $profitDisplay . '</td>
        </tr>';
    }

    if ($productCount === 0) {
        $html .= '
        <tr>
            <td colspan="5" align="center">
                No sales transactions were found for the selected reporting period.
            </td>
        </tr>';
    }

    $html .= '
        <tr style="font-weight:bold;background-color:#eeeeee;">
            <td>TOTAL</td>
            <td align="right">' . number_format($totalUnits, 0) . '</td>
            <td align="right">₱' . number_format($totalRevenue, 2) . '</td>
            <td align="right">₱' . number_format($totalCost, 2) . '</td>
            <td align="right">₱' . number_format($totalProfit, 2) . '</td>
        </tr>
    </table>';

    if ($missingCostProducts > 0) {
        $html .= '
        <p><b>Note:</b> ' . $missingCostProducts .
        ' product(s) have no recorded purchase unit cost. Their estimated costs and profits are shown as N/A and excluded from the cost and profit totals.</p>';
    }

    $html .= '
    <p><i>Estimated product cost is calculated by multiplying the ordered quantity from the latest recorded non-cancelled restock entry by its PurchaseUnitCost per unit. Gross profit is estimated by subtracting this product cost from sales revenue and excludes operating expenses. Since sales are not linked to specific restocking batches, this report may not reflect the exact historical cost of the items sold.</i></p>';

    $productStmt->close();
    $salesStmt->close();

    reportCreatePdf(
        'SALES AND PROFIT REPORT',
        $dateFrom,
        $dateTo,
        $generatedBy,
        $generatedAt,
        $recipient,
        $html,
        'sales_profit_report.pdf'
    );

} catch (Throwable $e) {
    error_log(
        'Sales and profit report error: ' .
        $e->getMessage() .
        ' in ' . $e->getFile() .
        ' on line ' . $e->getLine()
    );

    reportFail(
        'Unable to generate the report. Please check the server error log.',
        500
    );
}


<?php
if (session_status() !== PHP_SESSION_ACTIVE) {
    session_start();
}

date_default_timezone_set('Asia/Manila');

require_once __DIR__ . '/../connect.php';
require_once __DIR__ . '/../tcpdf/tcpdf.php';

function reportFail($message, $status = 400) {
    http_response_code($status);
    exit($message);
}

function reportDateIsValid($value) {
    $date = DateTime::createFromFormat('!Y-m-d', (string)$value);
    return $date && $date->format('Y-m-d') === $value;
}

$dateFrom = $_GET['date_from'] ?? '';
$dateTo = $_GET['date_to'] ?? '';
$recipient = trim((string)($_GET['recipient'] ?? ''));
$recipient = mb_substr($recipient, 0, 150);

if (!reportDateIsValid($dateFrom) || !reportDateIsValid($dateTo)) {
    reportFail('Please provide valid start and end dates.');
}

if ($dateFrom > $dateTo) {
    reportFail('The start date cannot be later than the end date.');
}

$generatedBy = trim((string)(
    $_SESSION['userName'] ??
    $_SESSION['username'] ??
    $_SESSION['user_name'] ??
    ''
));

if ($generatedBy === '') {
    $generatedBy = 'Authenticated System User';
}

$generatedAt = date('F j, Y g:i A');

function reportCreatePdf($title, $dateFrom, $dateTo, $generatedBy, $generatedAt, $recipient, $tableHtml, $filename) {
    $pdf = new TCPDF('L', 'mm', 'A4', true, 'UTF-8', false);

    $pdf->SetCreator('Inventory and Sales Management System');
    $pdf->SetAuthor($generatedBy);
    $pdf->SetTitle($title);
    $pdf->SetMargins(10, 12, 10);
    $pdf->SetAutoPageBreak(true, 18);
    $pdf->SetFont('dejavusans', '', 10);
    $pdf->AddPage();

    $html = '
    <h2 style="text-align:center;">MVM DAEGU SUPERMARKET CORP.</h2>
    <h3 style="text-align:center;">' . htmlspecialchars($title, ENT_QUOTES, 'UTF-8') . '</h3>
    <p style="text-align:center;">Reporting Period: ' .
        htmlspecialchars(date('F j, Y', strtotime($dateFrom)), ENT_QUOTES, 'UTF-8') .
        ' to ' .
        htmlspecialchars(date('F j, Y', strtotime($dateTo)), ENT_QUOTES, 'UTF-8') .
    '</p><br>' . $tableHtml . '<br><br>
    <table cellpadding="5">
        <tr>
            <td width="50%">
                Generated by:<br><br><br>
                <b>' . htmlspecialchars($generatedBy, ENT_QUOTES, 'UTF-8') . '</b><br>
                System User<br>
                Generated on: ' . htmlspecialchars($generatedAt, ENT_QUOTES, 'UTF-8') . '
            </td>
            <td width="50%">
                Presented to / Received by:<br><br><br>
                <b>' . htmlspecialchars($recipient, ENT_QUOTES, 'UTF-8') . '</b><br>
                Signature: ______________________________<br><br>
                Date received: __________________________
            </td>
        </tr>
    </table>';

    $pdf->writeHTML($html, true, false, true, false, '');

    if (ob_get_level() > 0) {
        ob_clean();
    }

    $pdf->Output($filename, 'I');
    exit;
}

function reportSum($connection, $sql) {
    $result = $connection->query($sql);

    if (!$result) {
        throw new RuntimeException($connection->error);
    }

    $row = $result->fetch_assoc();

    return (float)($row['total'] ?? 0);
}

function movementSum($connection, $table, $quantityColumn, $dateColumn, $productId, $from, $to) {
    $allowed = [
        'restock' => ['TotalReceived', 'Date_Received'],
        'sales_item_test' => ['Quantity', 'date_created'],
        'customersreturns' => ['Quantity', 'ReturnedDate'],
        'supplierreturns' => ['Quantity', 'ReturnedDate'],
        'pulledoutitems' => ['Quantity', 'PulledDate']
    ];

    if (
        !isset($allowed[$table]) ||
        $allowed[$table][0] !== $quantityColumn ||
        $allowed[$table][1] !== $dateColumn
    ) {
        throw new RuntimeException('Unsupported movement source.');
    }

    $pid = (int)$productId;
    $from = $connection->real_escape_string($from);
    $to = $connection->real_escape_string($to);

    $dateCondition = "DATE(`$dateColumn`) BETWEEN '$from' AND '$to'";

    if ($table === 'restock') {
        $dateCondition .= " AND `Date_Received` IS NOT NULL";
    }

    return reportSum($connection, "
        SELECT SUM(COALESCE(`$quantityColumn`, 0)) AS total
        FROM `$table`
        WHERE Product_ID = $pid AND $dateCondition
    ");
}

try {
    if (!isset($conn, $conn_pos)) {
        throw new RuntimeException('Expected $conn and $conn_pos connections.');
    }

    $result = $conn->query("
        SELECT Product_ID, ProductName, CurrentStock
        FROM product
        ORDER BY ProductName
    ");

    if (!$result) {
        throw new RuntimeException($conn->error);
    }

    $html = '<table border="1" cellpadding="4">
    <tr style="font-weight:bold;background-color:#eeeeee;">
        <th width="25%">Product</th>
        <th width="11%">Opening Stock</th>
        <th width="10%">Stock In</th>
        <th width="10%">Units Sold</th>
        <th width="12%">Customer Returns</th>
        <th width="12%">Supplier Returns</th>
        <th width="9%">Pulled Out</th>
        <th width="11%">Closing Stock</th>
    </tr>';

    $dayAfterEnd = date('Y-m-d', strtotime($dateTo . ' +1 day'));

    while ($product = $result->fetch_assoc()) {
        $pid = (int)$product['Product_ID'];
        $current = (float)$product['CurrentStock'];

        $receivedAfter = movementSum($conn, 'restock', 'TotalReceived', 'Date_Received', $pid, $dayAfterEnd, '9999-12-31');
        $soldAfter = movementSum($conn_pos, 'sales_item_test', 'Quantity', 'date_created', $pid, $dayAfterEnd, '9999-12-31');
        $customerAfter = movementSum($conn, 'customersreturns', 'Quantity', 'ReturnedDate', $pid, $dayAfterEnd, '9999-12-31');
        $supplierAfter = movementSum($conn, 'supplierreturns', 'Quantity', 'ReturnedDate', $pid, $dayAfterEnd, '9999-12-31');
        $pulledAfter = movementSum($conn, 'pulledoutitems', 'Quantity', 'PulledDate', $pid, $dayAfterEnd, '9999-12-31');

        $closing = $current - $receivedAfter + $soldAfter - $customerAfter + $supplierAfter + $pulledAfter;

        $received = movementSum($conn, 'restock', 'TotalReceived', 'Date_Received', $pid, $dateFrom, $dateTo);
        $sold = movementSum($conn_pos, 'sales_item_test', 'Quantity', 'date_created', $pid, $dateFrom, $dateTo);
        $customer = movementSum($conn, 'customersreturns', 'Quantity', 'ReturnedDate', $pid, $dateFrom, $dateTo);
        $supplier = movementSum($conn, 'supplierreturns', 'Quantity', 'ReturnedDate', $pid, $dateFrom, $dateTo);
        $pulled = movementSum($conn, 'pulledoutitems', 'Quantity', 'PulledDate', $pid, $dateFrom, $dateTo);

        $opening = $closing - $received + $sold - $customer + $supplier + $pulled;

        $html .= '<tr>
            <td>' . htmlspecialchars($product['ProductName'], ENT_QUOTES, 'UTF-8') . '</td>
            <td align="right">' . number_format($opening, 0) . '</td>
            <td align="right">' . number_format($received, 0) . '</td>
            <td align="right">' . number_format($sold, 0) . '</td>
            <td align="right">' . number_format($customer, 0) . '</td>
            <td align="right">' . number_format($supplier, 0) . '</td>
            <td align="right">' . number_format($pulled, 0) . '</td>
            <td align="right">' . number_format($closing, 0) . '</td>
        </tr>';
    }

    $html .= '</table>';

    reportCreatePdf(
        'HISTORICAL INVENTORY REPORT',
        $dateFrom,
        $dateTo,
        $generatedBy,
        $generatedAt,
        $recipient,
        $html,
        'historical_inventory_report.pdf'
    );

} catch (Throwable $e) {
    error_log('Historical inventory report: ' . $e->getMessage());
    reportFail(
        'Unable to generate the report. Verify database connections, TCPDF path, and movement table columns.',
        500
    );
}
